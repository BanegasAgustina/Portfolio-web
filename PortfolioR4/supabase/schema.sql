-- Ejecutar en SQL Editor de Supabase. No borra contenido existente.
begin;
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
create table if not exists private.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table private.admin_users enable row level security;
revoke all on private.admin_users from public, anon, authenticated;
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from private.admin_users where user_id = (select auth.uid()));
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

create or replace function public.valid_link(value text) returns boolean
language sql immutable set search_path = '' as $$
  select value = '' or (value ~ '^https?://[^[:space:]]+$');
$$;
create or replace function public.valid_image(value text) returns boolean
language sql immutable set search_path = '' as $$
  select value = '' or value ~ '^https://[^[:space:]]+$';
$$;
create table if not exists public.profile (
  id bigint primary key default 1 check (id = 1),
  name text not null check (length(name) between 2 and 160),
  role text not null check (length(role) between 2 and 200),
  description text not null check (length(description) between 10 and 6000),
  tagline text not null default '' check (length(tagline) <= 240),
  location text not null default '' check (length(location) <= 200),
  avatar text not null default '' check (public.valid_image(avatar)),
  cv text not null default '' check (public.valid_link(cv) or cv ~ '^/cv/[a-zA-Z0-9_-]+\.pdf$'),
  phone text not null default '' check (length(phone) <= 40),
  show_phone boolean not null default false,
  created_at timestamptz not null default now()
);
-- La tabla de perfil no se lee públicamente: el RPC elimina el teléfono oculto.
create or replace function public.get_public_profile() returns jsonb
language sql stable security definer set search_path = '' as $$
  select case when p.show_phone then to_jsonb(p) else to_jsonb(p) - 'phone' end
  from public.profile p where p.id = 1;
$$;
revoke all on function public.get_public_profile() from public;
grant execute on function public.get_public_profile() to anon, authenticated;
create or replace function public.save_profile(record jsonb) returns jsonb
language plpgsql security invoker set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Acceso no autorizado' using errcode = '42501'; end if;
  insert into public.profile(id,name,role,description,tagline,location,avatar,cv,phone,show_phone)
  values(1,record->>'name',record->>'role',record->>'description',coalesce(record->>'tagline',''),coalesce(record->>'location',''),coalesce(record->>'avatar',''),coalesce(record->>'cv',''),coalesce(record->>'phone',''),coalesce((record->>'show_phone')::boolean,false))
  on conflict(id) do update set name=excluded.name,role=excluded.role,description=excluded.description,tagline=excluded.tagline,location=excluded.location,avatar=excluded.avatar,cv=excluded.cv,phone=excluded.phone,show_phone=excluded.show_phone;
  return jsonb_build_object('id',1);
end;
$$;
revoke all on function public.save_profile(jsonb) from public;
grant execute on function public.save_profile(jsonb) to authenticated;

