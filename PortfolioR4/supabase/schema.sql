-- Grants mínimos y RLS para CADA tabla expuesta. Una cuenta registrada no es admin.
do $$
declare t text;
begin
  foreach t in array array['profile','projects','skills','experiences','education','social_links','soft_skills','contact_messages'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('revoke all on public.%I from anon, authenticated',t);
    execute format('grant select,insert,update,delete on public.%I to authenticated',t);
    execute format('drop policy if exists admin_content on public.%I',t);
    execute format('create policy admin_content on public.%I for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()))',t);
    if t not in ('profile','contact_messages') then
      execute format('grant select on public.%I to anon',t);
      execute format('drop policy if exists public_read on public.%I',t);
      execute format('create policy public_read on public.%I for select to anon,authenticated using (true)',t);
    end if;
  end loop;
end $$;
grant usage on schema public to anon,authenticated;
grant usage,select on all sequences in schema public to authenticated;
-- Sólo el backend opcional de contacto usa una clave secreta del servidor.
grant insert on public.contact_messages to service_role;
grant usage,select on sequence public.contact_messages_id_seq to service_role;
create index if not exists projects_order on public.projects(is_featured desc,display_order,id);
create index if not exists messages_date on public.contact_messages(created_at desc);

